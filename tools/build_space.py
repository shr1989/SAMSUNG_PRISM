"""Assemble a ready-to-push Hugging Face Space folder from the repository (copies only).

    python tools/build_space.py            # -> build/huggingface_space/
Then push that folder's contents to a Gradio Space (see deploy/huggingface_space/DEPLOY.md).
"""

import argparse
import hashlib
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEMPLATE = ROOT / "deploy" / "huggingface_space"
FILES = {
    "app.py": "app.py",
    "src/__init__.py": "src/__init__.py",
    "src/config.py": "src/config.py",
    "src/extract_keypoints.py": "src/extract_keypoints.py",
    "src/preprocess.py": "src/preprocess.py",
    "src/inference.py": "src/inference.py",
    "models/exported/model_fp32.onnx": "models/exported/model_fp32.onnx",
    "data/processed/preprocess_config.json": "data/processed/preprocess_config.json",
    "data/processed/manifest.csv": "data/processed/manifest.csv",
}
TEMPLATE_FILES = ("README.md", "requirements.txt", "packages.txt")
MARKER = ".echogesture_space"


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, default=ROOT / "build" / "huggingface_space")
    args = parser.parse_args()
    out = args.out.resolve()
    if out.exists():
        if not (out / MARKER).exists():
            raise SystemExit(
                f"{out} exists and was not created by this script; choose another --out"
            )
        shutil.rmtree(out)
    out.mkdir(parents=True)
    (out / MARKER).write_text("generated by tools/build_space.py\n")
    for source, target in FILES.items():
        (out / target).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(ROOT / source, out / target)
        assert digest(ROOT / source) == digest(out / target)
    for name in TEMPLATE_FILES:
        shutil.copy2(TEMPLATE / name, out / name)
    size = sum(p.stat().st_size for p in out.rglob("*") if p.is_file()) / 2**20
    print(f"Space folder ready: {out} ({size:.1f} MB)")


if __name__ == "__main__":
    main()
