def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def copy(source: Path, target: Path) -> None:
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(source, target)


def assemble(bundle: Path, rebuild: bool) -> None:
    if bundle.exists():
        if not (rebuild and (bundle / MARKER).exists()):
            raise SystemExit(f"{bundle} exists; pass --rebuild to replace a previous build")
        shutil.rmtree(bundle)
    bundle.mkdir(parents=True)
    (bundle / MARKER).write_text("generated by tools/build_submission.py\n")
    for name in SRC_MODULES:
        copy(ROOT / "src" / name, bundle / "src" / name)
    for source, target in COPIES.items():
        copy(ROOT / source, bundle / target)
    for name in REPORTS:
        copy(ROOT / "results" / "reports" / name, bundle / "results" / "reports" / name)
    for source, target in TEMPLATE_FILES.items():
        copy(TEMPLATES / source, bundle / target)
    relativise_report_paths(bundle)
    best = bundle / "models/checkpoints/tcnn/best.pt"
    print(f"assembled {bundle}; best.pt sha256 {sha256(best)[:16]}")


def relativise_report_paths(bundle: Path) -> None:
    # Copies only: path metadata in reports becomes relative to the bundle root; values unchanged.
    prefix = f"{ROOT}/"
    for path in (bundle / "results" / "reports").iterdir():
        text = path.read_text()
        if prefix in text:
            path.write_text(text.replace(prefix, ""))


def paired_bootstrap_ci(rows: pd.DataFrame, seed: int = 42, draws: int = 10_000) -> tuple:
    clean = rows["clean_top1"].to_numpy(float)
    occluded = rows["occluded_top1"].to_numpy(float)
    rng = np.random.default_rng(seed)
    index = rng.integers(0, len(rows), (draws, len(rows)))
    drops = 100 * (clean[index].mean(1) - occluded[index].mean(1))
    return float(np.percentile(drops, 2.5)), float(np.percentile(drops, 97.5))


