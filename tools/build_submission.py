def write_checksums(bundle: Path) -> None:
    lines = [
        f"{sha256(path)}  {path.relative_to(bundle).as_posix()}"
        for path in sorted(bundle.rglob("*"))
        if path.is_file()
        and path.name not in (MARKER, "SHA256SUMS.txt")
        and "__pycache__" not in path.parts
        and path.name != ".DS_Store"
    ]
    (bundle / "SHA256SUMS.txt").write_text("\n".join(lines) + "\n")


def make_zip(bundle: Path) -> Path:
    write_checksums(bundle)
    target = bundle.with_suffix(".zip")
    if target.exists():
        target.unlink()
    with zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED) as archive:
        for path in sorted(bundle.rglob("*")):
            skip = path.name in (MARKER, ".DS_Store") or "__pycache__" in path.parts
            if path.is_file() and not skip:
                archive.write(path, Path(bundle.name) / path.relative_to(bundle))
    print(f"{target} {target.stat().st_size / 2**20:.2f} MB")
    return target


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("step", choices=["assemble", "results", "zip"])
    parser.add_argument("--name", default="team_name")
    parser.add_argument("--rebuild", action="store_true")
    args = parser.parse_args()
    bundle = OUT_DIR / args.name
    if args.step == "assemble":
        assemble(bundle, args.rebuild)
    elif args.step == "results":
        results(bundle)
    else:
        make_zip(bundle)


if __name__ == "__main__":
    main()
